# Builds assets/fonts/MyExIcons.ttf + lib/core/design/my_ex_icons.dart from the shared
# Iconsax-style SVGs (Doxygene, yayaexpress, nodo) and assets/icons-src/.
# Run from myex_app/: python -I tool/build_icons.py  (needs picosvg, fonttools, pillow)
import os, sys, re
from picosvg.svg import SVG
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path

H=os.path.expanduser('~/AndroidStudioProjects')
D=H+'/Doxygene-Flutter/assets/icons/svg/'; Y=H+'/yayaexpess-marketplace/assets/icons/svg/'; N=H+'/nodo_mobile_app/assets/icons/'; O='assets/icons-src/'
MAP = [  # name, source
 ('back', D+'chevron_left.svg'), ('forward', Y+'chevron_right.svg'),
 ('check', O+'check.svg'), ('close', O+'close.svg'),
 ('lock', D+'lock_linear.svg'), ('unlock', O+'unlock.svg'),
 ('edit', D+'edit_2.svg'), ('bell', D+'notification_bing.svg'),
 ('heart', Y+'heart.svg'), ('heartFilled', N+'deal_heart_active.svg'),
 ('fire', Y+'fire.svg'), ('clock', D+'clock_outline.svg'),
 ('chat', D+'message_text.svg'), ('calendar', D+'calendar.svg'),
 ('journal', D+'note.svg'), ('arrowRight', O+'arrowRight.svg'),
 ('arrowUp', O+'arrowUp.svg'), ('star', D+'star.svg'),
 ('support', D+'messages.svg'), ('shield', D+'shield.svg'),
 ('restore', D+'refresh.svg'), ('call', D+'call.svg'),
 ('user', D+'user.svg'), ('chart', O+'chart.svg'),
 ('home', D+'home.svg'), ('homeFilled', D+'tab_home_active.svg'),
 ('list', D+'list_bullet.svg'), ('moon', O+'moon.svg'),
 ('card', D+'card.svg'), ('copy', O+'copy.svg'),
 ('checkCircle', D+'tick_circle_bold.svg'), ('gift', O+'gift.svg'),
 ('compose', D+'note_add.svg'), ('search', D+'search_normal.svg'),
]
UPM=1000; PAD=0.08
fb=FontBuilder(UPM, isTTF=True)
names=['.notdef']+[n for n,_ in MAP]
fb.setupGlyphOrder(names)
cmap={0xE000+i:n for i,(n,_) in enumerate(MAP)}
fb.setupCharacterMap(cmap)
glyphs={}; metrics={}
pen=TTGlyphPen(None); glyphs['.notdef']=pen.glyph(); metrics['.notdef']=(UPM,0)
for name,src in MAP:
    svg=SVG.parse(src).topicosvg()
    vb=svg.view_box()
    sc=UPM*(1-2*PAD)/max(vb.w,vb.h)
    ox=(UPM-vb.w*sc)/2 - vb.x*sc; oy=(UPM-vb.h*sc)/2 - vb.y*sc
    tt=TTGlyphPen(None)
    pen=TransformPen(Cu2QuPen(tt, max_err=1.0, reverse_direction=True), (sc,0,0,-sc,ox,UPM-oy))
    n=0
    for shape in svg.shapes():
        parse_path(shape.as_path().d, pen); n+=1
    glyphs[name]=tt.glyph(); metrics[name]=(UPM,0)
    print(name, n, 'paths', round(vb.w,1), round(vb.h,1))
fb.setupGlyf(glyphs); fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=UPM, descent=0)
fb.setupNameTable({'familyName':'MyExIcons','styleName':'Regular'})
fb.setupOS2(sTypoAscender=UPM, sTypoDescender=0, usWinAscent=UPM, usWinDescent=0)
fb.setupPost()
fb.save('assets/fonts/MyExIcons.ttf')
# dart
lines=["import 'package:flutter/widgets.dart';","","// GENERATED by the icon build (tool/build_icons.py). Do not edit by hand.","// Iconsax-style outline icons shared with the Doxygene, yayaexpress and nodo apps,","// compiled into the MyExIcons font so they work anywhere an IconData does.","abstract final class MyExIcons {","  static const _f = 'MyExIcons';"]
for i,(n,src) in enumerate(MAP):
    lines.append(f"  static const IconData {n} = IconData(0x{0xE000+i:x}, fontFamily: _f);")
lines.append('}')
open('lib/core/design/my_ex_icons.dart','w').write('\n'.join(lines)+'\n')
# preview
from PIL import Image, ImageDraw, ImageFont
f=ImageFont.truetype('assets/fonts/MyExIcons.ttf',64); lf=ImageFont.load_default()
cols=8; rows=(len(MAP)+cols-1)//cols
im=Image.new('RGB',(cols*110,rows*110),'white'); d=ImageDraw.Draw(im)
for i,(n,_) in enumerate(MAP):
    x=(i%cols)*110; y=(i//cols)*110
    d.text((x+23,y+8),chr(0xE000+i),font=f,fill='black'); d.text((x+4,y+92),n,font=lf,fill='gray')
im.save('build/icon_preview.png')
